const mongoose = require('mongoose');

const questionSchema = new mongoose.Schema({
  type: String, // 'mcq', 'fill_blank', 'enumeration'
  question: String,
  options: [String], // Populated only if type is 'mcq'
  answer: String // The correct answer generated by the AI
});

const assignmentSchema = new mongoose.Schema({
  courseCode: String,
  title: String,
  instructions: String,
  deadline: Date,
  autoClose: Boolean,
  maxGrade: Number,
  type: { type: String, default: 'Assignment' }, // Distinguishes between 'Assignment' and 'Quiz'
  questions: [questionSchema], // The AI-generated questions
  attachedFiles: [{ title: String, fileUrl: String }]
  // Submissions array removed to use separate model
});

module.exports = mongoose.model('Assignment', assignmentSchema);